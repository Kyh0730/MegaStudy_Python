a = 200
b = 10

# 더하기 연산
result = a + b
print(a, "+", b, "=", result)

# 빼기
result = a - b
print(a, "-", b, "=", result)

# 곱하기
result = a * b
print(a, "*", b, "=", result)

# 나누기
result = a / b
print(a, "/", b, "=", result)


